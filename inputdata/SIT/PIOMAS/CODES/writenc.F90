  SUBROUTINE writenc(CF,X,Y,MM,LON,LAT,V)
USE NETCDF
  IMPLICIT NONE
  CHARACTER(LEN=*), INTENT(IN) :: CF
  INTEGER, INTENT(IN) :: X,Y,MM
  REAL, DIMENSION(X,Y,MM), INTENT(IN) :: V
  REAL, DIMENSION(X,Y), INTENT(IN) :: LON
  REAL, DIMENSION(X,Y), INTENT(IN) :: LAT

  INTEGER :: XD, YD, ZD, TD, NCID, VD(4), VDIM(3)

  CALL CHECK( NF90_CREATE(CF, NF90_64BIT_OFFSET, NCID) )
  CALL CHECK( NF90_DEF_DIM(NCID, 'x', X, XD) )
  CALL CHECK( NF90_DEF_DIM(NCID, 'y', Y, YD) )
  CALL CHECK( NF90_DEF_DIM(NCID, 'time', NF90_UNLIMITED, TD) )
  VDIM = (/XD, YD, TD /)
  CALL CHECK( NF90_DEF_VAR(NCID, 'lon', NF90_REAL, VDIM(1:2), VD(1) ) )
  CALL CHECK( NF90_DEF_VAR(NCID, 'lat', NF90_REAL, VDIM(1:2), VD(2) ) )

  CALL CHECK( NF90_DEF_VAR(NCID, 'ice_thickness', NF90_REAL, VDIM, VD(4) ) )
  CALL CHECK( NF90_PUT_ATT(NCID, VD(1), 'units','degrees_east') )
  CALL CHECK( NF90_PUT_ATT(NCID, VD(1), 'long_name','longitude') )
  CALL CHECK( NF90_PUT_ATT(NCID, VD(2), 'units','degrees_north') )
  CALL CHECK( NF90_PUT_ATT(NCID, VD(2), 'long_name','latitude') )
  CALL CHECK( NF90_ENDDEF(NCID) )
  CALL CHECK( NF90_PUT_VAR(NCID, VD(1), LON) )
  CALL CHECK( NF90_PUT_VAR(NCID, VD(2), LAT) )

  CALL CHECK( NF90_PUT_VAR(NCID, VD(4), V) )
  CALL CHECK( NF90_CLOSE(NCID) )

  END SUBROUTINE writenc

  SUBROUTINE CHECK(STATUS)
    USE NETCDF
    IMPLICIT NONE
    INTEGER, INTENT ( IN) :: STATUS
    IF(STATUS /= NF90_NOERR) THEN
      WRITE(*,*) TRIM(NF90_STRERROR(STATUS))
      CALL ABORT
    END IF
  END SUBROUTINE CHECK
