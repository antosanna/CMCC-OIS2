PROGRAM READ
USE NETCDF
IMPLICIT NONE
INTEGER, PARAMETER :: NX=360, NY=120
INTEGER :: I,J
INTEGER :: TOPO(NX,NY)
INTEGER :: NCID, XD, YD, VDIM(2), VD

OPEN(21,FILE='io.dat_360_120.output')
DO J=1,NY
  READ(21,'(360I2)') TOPO(1:360,J)
ENDDO
CLOSE(21)

DO J=1,NY
 DO I=1,NX
  WRITE(*,*) I, J, TOPO(I,J)
 ENDDO
ENDDO

  CALL CHECK( NF90_CREATE('lsm_piomas.nc', NF90_64BIT_OFFSET, NCID) )
  CALL CHECK( NF90_DEF_DIM(NCID, 'x', NX, XD) )
  CALL CHECK( NF90_DEF_DIM(NCID, 'y', NY, YD) )
  VDIM = (/XD, YD /)
  CALL CHECK( NF90_DEF_VAR(NCID, 'lsm', NF90_INT, VDIM, VD ) )
  CALL CHECK( NF90_ENDDEF(NCID) )
  CALL CHECK( NF90_PUT_VAR(NCID, VD, TOPO) )
  CALL CHECK( NF90_CLOSE(NCID) )

CONTAINS
  SUBROUTINE CHECK(STATUS)
    USE NETCDF
    IMPLICIT NONE
    INTEGER, INTENT ( IN) :: STATUS
    IF(STATUS /= NF90_NOERR) THEN
      WRITE(*,*) TRIM(NF90_STRERROR(STATUS))
      CALL ABORT
    END IF
  END SUBROUTINE CHECK

END PROGRAM READ
